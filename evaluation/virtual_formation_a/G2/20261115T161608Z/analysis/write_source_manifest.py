"""Write the G2 source-and-evidence manifest.

The manifest binds every G2 source/test/fixture file, every file in this
evidence run (except three self-referential artifacts), the accepted G1 and G0
snapshots, the protected-tree diff and the frozen acceptance results.  The
independent verifier recomputes all of it from disk.
"""
import datetime
import hashlib
import json
from pathlib import Path
import subprocess

RUN = Path(__file__).resolve().parents[1]
REPO_ROOT = Path(__file__).resolve().parents[5]
RUN_ID = RUN.name
SCHEMA = "virtual_rigid_a.g2.source_manifest.v1"
STAGE = "G2"
BASELINE_HEAD = "567bdecba9676313da3bc9a97b82f57b5b569a2b"
G1_ACCEPTANCE = (REPO_ROOT / "evaluation/virtual_formation_a/G1" /
                 "codex_acceptance_rework_01/CODEX_ACCEPTANCE.json")
G1_RUN = REPO_ROOT / "evaluation/virtual_formation_a/G1/20261115T152858Z"
G1_MANIFEST = G1_RUN / "source_manifest.json"
G1_PROTECTED = G1_RUN / "legacy/protected_after.json"
G0_SNAPSHOT = (REPO_ROOT / "evaluation/virtual_formation_a/G0" /
               "20261115T143321Z_rework/protected_before.json")
EXPECTED_G1_MANIFEST_SHA = (
    "fa6ca4387bf57d35f76097f5e50c23715bf72256f186707b59f4e1ec4262718a")
EXPECTED_G1_TREE = (
    "910efe32972dcbcb3a0c2585c002916ede878f4295b0f26b4dc917faeee4f519")
EXPECTED_G1_AFTER_SHA = (
    "c9e4c874c3e7d0dc05a1850d74febd28ec7475a232b6f8f98d3e1c11d2892470")
EXPECTED_G0_SHA = (
    "a89efe0887eb20aced4bad74bc8adf280079191b9c491436e2ae4e89c2506c9a")
EXPECTED_G0_TREE = (
    "ff58f2b5c6acfbc207327202f875e5e9a20734ef09ebb6070ee07edce6ebf091")
PACKAGE = ("catkin_ws/src/fwis_v3_optimizer/src/fwis_v3_optimizer/"
           "formation_continuous_a/")
G2_SOURCES = [
    PACKAGE + "audit.py",
    PACKAGE + "optimizer.py",
    "docs/virtual_formation_a/CLAUDE_G2_TASK.md",
    "tests/fixtures/virtual_a/existence_reference.json",
    "tests/fixtures/virtual_a/open_requests.json",
    "tests/test_virtual_a_audit.py",
    "tests/test_virtual_a_optimizer.py",
]
REFERENCE_DOCUMENTS = [
    "docs/VIRTUAL_FORMATION_A_FR06_TECHNICAL_REVIEW_20261115.md",
]
EXCLUSIONS = [
    "source_manifest.json",
    "logs/source_manifest_generation.log",
    "logs/source_manifest_verification.log",
]
EXPECTED_CHANGED = sorted([
    PACKAGE + "contracts.py",
    "tools/virtual_a_benchmark.py",
])
EXPECTED_TEST_COUNTS = {
    "audit": 20, "optimizer": 12, "g1_geometry": 20, "g1_profile": 22}
EXPECTED_CHECK_COUNT = 97


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def file_record(path):
    path = Path(path)
    return {"bytes": path.stat().st_size, "sha256": sha256(path)}


def canonical_protected_tree(snapshot):
    payload = {
        entry["path"]: {
            "type": entry["type"],
            "sha256": entry["sha256"],
            "size_bytes": entry["size_bytes"],
        }
        for entry in snapshot["protected_files"]
    }
    return hashlib.sha256(json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
        allow_nan=False).encode("utf-8")).hexdigest()


def git(*args):
    return subprocess.run(
        ["git"] + list(args), cwd=str(REPO_ROOT), check=True,
        capture_output=True, text=True).stdout


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def main():
    for required in ("CLAUDE_REPORT.md", "COMMANDS.md", "environment.json",
                     "results.json", "frozen/frozen_manifest.json",
                     "analysis/attempts.json",
                     "analysis/acceptance_summary.json",
                     "analysis/protection_diff_vs_g1_accepted.json",
                     "logs/source_manifest_generation.log"):
        if not (RUN / required).is_file():
            raise SystemExit("missing evidence before manifest: " + required)
    pycache = [path for path in RUN.rglob("*")
               if path.name == "__pycache__"
               or path.suffix in (".pyc", ".pyo")]
    if pycache:
        raise SystemExit("generated bytecode exists under the run: {}".format(
            [str(path) for path in pycache[:3]]))
    source_pycache = [path for path in REPO_ROOT.rglob("*")
                      if path.name == "__pycache__"
                      and "evaluation" not in path.parts]
    if source_pycache:
        raise SystemExit("generated bytecode exists in source: {}".format(
            [str(path) for path in source_pycache[:3]]))

    acceptance = load(G1_ACCEPTANCE)
    if acceptance.get("status") != "ACCEPTED":
        raise SystemExit("G1 acceptance is not ACCEPTED")
    if acceptance.get("source_manifest_sha256") != EXPECTED_G1_MANIFEST_SHA:
        raise SystemExit("G1 acceptance does not bind the G1 manifest")
    if acceptance.get("next_stage_authorized") is not False:
        raise SystemExit("G1 acceptance unexpectedly authorizes G3")
    if sha256(G1_MANIFEST) != EXPECTED_G1_MANIFEST_SHA:
        raise SystemExit("accepted G1 source manifest changed")
    g1_manifest = load(G1_MANIFEST)
    excluded_g1 = set(g1_manifest["excluded_self_referential"])
    g1_run_mismatches = []
    for relative, record in sorted(g1_manifest["run_files"].items()):
        if relative in excluded_g1:
            continue
        path = G1_RUN / relative
        if not path.is_file() or sha256(path) != record["sha256"]:
            g1_run_mismatches.append(relative)
    if g1_run_mismatches:
        raise SystemExit("accepted G1 run files changed: {}".format(
            g1_run_mismatches[:3]))
    g1_snapshot = load(G1_PROTECTED)
    if sha256(G1_PROTECTED) != EXPECTED_G1_AFTER_SHA:
        raise SystemExit("accepted G1 protected_after.json changed")
    if g1_snapshot["protected_tree_sha256"] != EXPECTED_G1_TREE:
        raise SystemExit("accepted G1 protected tree changed")
    if canonical_protected_tree(g1_snapshot) != EXPECTED_G1_TREE:
        raise SystemExit("accepted G1 protected snapshot is inconsistent")

    g0 = load(G0_SNAPSHOT)
    if sha256(G0_SNAPSHOT) != EXPECTED_G0_SHA:
        raise SystemExit("accepted G0 protected snapshot changed")
    if g0["protected_tree_sha256"] != EXPECTED_G0_TREE:
        raise SystemExit("accepted G0 protected tree changed")
    if canonical_protected_tree(g0) != EXPECTED_G0_TREE:
        raise SystemExit("accepted G0 protected snapshot is inconsistent")

    g1_sources = dict(g1_manifest["source_files"])
    source_paths = sorted(set(g1_sources) | set(G2_SOURCES))
    if len(source_paths) != 22:
        raise SystemExit("expected 22 source files, got {}".format(
            len(source_paths)))
    source_files = {
        relative: file_record(REPO_ROOT / relative)
        for relative in source_paths}
    changed_sources = {}
    for relative in sorted(g1_sources):
        old_hash = g1_sources[relative]["sha256"]
        new_hash = source_files[relative]["sha256"]
        changed_sources[relative] = {
            "g1_sha256": old_hash,
            "current_sha256": new_hash,
            "changed": old_hash != new_hash,
        }
    actually_changed = sorted(
        path for path, record in changed_sources.items() if record["changed"])
    if actually_changed != EXPECTED_CHANGED:
        raise SystemExit("unexpected changes to accepted G1 source files: "
                         "{}".format(actually_changed))
    for relative in G2_SOURCES:
        if relative in g1_sources:
            raise SystemExit("new G2 source was already in G1 manifest: " +
                             relative)
    reference_files = {
        relative: file_record(REPO_ROOT / relative)
        for relative in REFERENCE_DOCUMENTS}

    protection_path = (RUN / "analysis" /
                       "protection_diff_vs_g1_accepted.json")
    protection = load(protection_path)
    if not protection["authorization"]["only_authorized_changes"]:
        raise SystemExit("protection diff is not exactly authorized")
    if protection["removed_vs_g1_accepted"]:
        raise SystemExit("protected removals are present")
    added = sorted(row["path"] for row in protection["added_vs_g1_accepted"])
    if added != sorted(protection["authorization"]["allowed_new_files"]):
        raise SystemExit("protected additions differ from the G2 whitelist")
    changed = sorted(row["path"] for row in protection[
        "changed_vs_g1_accepted"])
    if changed != EXPECTED_CHANGED:
        raise SystemExit("protected tracked changes differ from authorization")
    if protection["current"]["unchanged_common_tree_matches"] is not True:
        raise SystemExit("unchanged common protected tree does not match")

    results = load(RUN / "results.json")
    acceptance_summary = load(RUN / "analysis/acceptance_summary.json")
    attempts = load(RUN / "analysis/attempts.json")
    benchmark = load(RUN / "benchmark/summary.json")
    frozen = load(RUN / "frozen/frozen_manifest.json")
    if results["status"] != "PASS_PENDING_CODEX_RECHECK":
        raise SystemExit("results status is not pending Codex recheck")
    if results["codex_acceptance"] != "NOT_RUN_NOT_CLAIMED":
        raise SystemExit("results self-claim Codex acceptance")
    if results["scope"]["output_status"] != "GEOMETRY_FEASIBLE only":
        raise SystemExit("results scope is not the G2 geometry scope")
    for key in ("timing", "dynamics", "map"):
        if results["scope"][key] != "NOT_EVALUATED":
            raise SystemExit("scope {} was not left NOT_EVALUATED".format(key))
    if results["scope"]["ros_execution"] != "NOT_RUN":
        raise SystemExit("ROS execution was claimed")
    if results["scope"]["executable_field"] != "NOT_PRESENT":
        raise SystemExit("an executable field was claimed")
    if acceptance_summary["all_requests_pass"] is not True:
        raise SystemExit("acceptance summary is not all-pass")
    if acceptance_summary["all_audits_passed"] is not True:
        raise SystemExit("not all independent audits passed")
    if acceptance_summary["all_requests_status"] != ["GEOMETRY_FEASIBLE"]:
        raise SystemExit("unexpected solve statuses")
    if acceptance_summary["deadline"]["any_deadline_exhausted"]:
        raise SystemExit("a deadline was exhausted")
    if acceptance_summary["maximums"]["endpoint_position_error_m"] > 0.005:
        raise SystemExit("position tolerance was exceeded")
    if acceptance_summary["maximums"]["endpoint_heading_error_rad"] > \
            0.003490658503988659:
        raise SystemExit("heading tolerance was exceeded")
    if acceptance_summary["maximums"]["rigidity_error_m"] > 1e-6:
        raise SystemExit("rigidity tolerance was exceeded")
    if acceptance_summary["maximums"]["position_budget_m"] > 1e-7:
        raise SystemExit("position integration budget was exceeded")
    if acceptance_summary["maximums"]["angle_budget_rad"] > 1e-9:
        raise SystemExit("angle integration budget was exceeded")
    if acceptance_summary["tests"] != {
            name: {
                "count": EXPECTED_TEST_COUNTS[name],
                "wall_time_s": acceptance_summary["tests"][name][
                    "wall_time_s"],
                "status": "OK"}
            for name in EXPECTED_TEST_COUNTS}:
        raise SystemExit("test counts/status changed in the summary")
    if benchmark["status"] != "PASS" or len(benchmark["checks"]) != \
            EXPECTED_CHECK_COUNT:
        raise SystemExit("benchmark is not 97/97 PASS")
    if any(not check["pass"] for check in benchmark["checks"]):
        raise SystemExit("benchmark contains a failed check")
    if frozen["planner_config"][
            "reconstructed_equals_PlannerConfig"] is not True:
        raise SystemExit("frozen config equality was not proven")
    if attempts["schema"] != "virtual_rigid_a.g2.attempts.v1":
        raise SystemExit("attempt register schema changed")
    if sum(record["attempt_count"]
           for record in attempts["requests"].values()) != 48:
        raise SystemExit("attempt register does not contain 48 attempts")

    run_files = {}
    for path in sorted(RUN.rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(RUN).as_posix()
        if relative in EXCLUSIONS:
            continue
        run_files[relative] = file_record(path)
    run_total_bytes = sum(record["bytes"] for record in run_files.values())

    status = git("status", "--short")
    head = git("rev-parse", "HEAD").strip()
    branch = git("rev-parse", "--abbrev-ref", "HEAD").strip()
    staged = git("diff", "--cached", "--binary")
    ancestor = subprocess.run(
        ["git", "merge-base", "--is-ancestor", BASELINE_HEAD, "HEAD"],
        cwd=str(REPO_ROOT), check=False).returncode
    if head != BASELINE_HEAD or branch != "feature/virtual-rigid-formation-a":
        raise SystemExit("unexpected git HEAD or branch")
    if ancestor != 0:
        raise SystemExit("baseline is not an ancestor")
    if staged:
        raise SystemExit("staged changes are present")

    manifest = {
        "schema": SCHEMA,
        "stage": STAGE,
        "generated_at_utc": datetime.datetime.now(
            datetime.timezone.utc).isoformat(),
        "run_id": RUN_ID,
        "repo_root": str(REPO_ROOT),
        "baseline_head": BASELINE_HEAD,
        "excluded_self_referential": EXCLUSIONS,
        "exclusion_reasons": {
            "source_manifest.json":
                "the manifest cannot hash itself",
            "logs/source_manifest_generation.log":
                "the generator writes this log while scanning the run",
            "logs/source_manifest_verification.log":
                "the verifier writes this log while checking the manifest",
        },
        "scope_note": (
            "G2 endpoint-driven continuous A geometry evidence only. "
            "GEOMETRY_FEASIBLE is not executable, timed, dynamic, collision, "
            "map, ROS or hardware acceptance. HEAD is unchanged and no commit, "
            "push, branch or G3 entry occurred."),
        "source_files": source_files,
        "source_file_count": len(source_files),
        "g2_source_files": sorted(G2_SOURCES),
        "reference_documents": reference_files,
        "reference_document_count": len(reference_files),
        "changed_accepted_sources": changed_sources,
        "changed_accepted_source_list": actually_changed,
        "run_files": run_files,
        "run_file_count": len(run_files),
        "run_total_bytes": run_total_bytes,
        "git": {
            "head": head,
            "branch": branch,
            "baseline_head": BASELINE_HEAD,
            "baseline_is_ancestor": True,
            "committed": "NO",
            "pushed": "NO",
            "branch_created": "NO",
            "status_short": status.splitlines(),
            "staged_diff_sha256": hashlib.sha256(
                staged.encode("utf-8")).hexdigest(),
        },
        "protected": {
            "g0_path": str(G0_SNAPSHOT.relative_to(REPO_ROOT)),
            "g0_sha256": sha256(G0_SNAPSHOT),
            "g0_tree_sha256": g0["protected_tree_sha256"],
            "g0_file_count": g0["protected_file_count"],
            "g0_unchanged": True,
            "g1_acceptance_path": str(G1_ACCEPTANCE.relative_to(REPO_ROOT)),
            "g1_acceptance_sha256": sha256(G1_ACCEPTANCE),
            "g1_acceptance_status": acceptance["status"],
            "g1_acceptance_next_stage_authorized":
                acceptance["next_stage_authorized"],
            "g1_run": str(G1_RUN.relative_to(REPO_ROOT)),
            "g1_manifest_sha256": sha256(G1_MANIFEST),
            "g1_manifest_run_files_checked": len(g1_manifest["run_files"]),
            "g1_manifest_run_files_all_match": True,
            "g1_protected_after_path":
                str(G1_PROTECTED.relative_to(REPO_ROOT)),
            "g1_protected_after_sha256": sha256(G1_PROTECTED),
            "g1_tree_sha256": g1_snapshot["protected_tree_sha256"],
            "g1_file_count": g1_snapshot["protected_file_count"],
            "comparison_path": str(protection_path.relative_to(RUN)),
            "comparison_sha256": sha256(protection_path),
            "added_vs_g1_accepted": added,
            "changed_vs_g1_accepted": changed,
            "removed_vs_g1_accepted": protection["removed_vs_g1_accepted"],
            "only_authorized_changes": True,
            "current_full_protected_tree_sha256":
                protection["current"]["full_protected_tree_sha256"],
            "unchanged_common_tree_sha256":
                protection["current"]["unchanged_common_tree_sha256_current"],
        },
        "results": {
            "status": results["status"],
            "codex_acceptance": results["codex_acceptance"],
            "request_count": len(results["request_names"]),
            "request_names": results["request_names"],
            "all_statuses": acceptance_summary["all_requests_status"],
            "all_audits_passed": acceptance_summary["all_audits_passed"],
            "attempt_count": results["attempts"]["count"],
            "benchmark_status": benchmark["status"],
            "benchmark_checks": len(benchmark["checks"]),
            "benchmark_failed": sum(
                not check["pass"] for check in benchmark["checks"]),
            "tests": {name: EXPECTED_TEST_COUNTS[name]
                      for name in EXPECTED_TEST_COUNTS},
            "maximum_endpoint_position_error_m":
                acceptance_summary["maximums"][
                    "endpoint_position_error_m"],
            "maximum_endpoint_heading_error_rad":
                acceptance_summary["maximums"][
                    "endpoint_heading_error_rad"],
            "maximum_rigidity_error_m":
                acceptance_summary["maximums"]["rigidity_error_m"],
            "maximum_position_budget_m":
                acceptance_summary["maximums"]["position_budget_m"],
            "maximum_angle_budget_rad":
                acceptance_summary["maximums"]["angle_budget_rad"],
            "maximum_abs_C":
                acceptance_summary["maximums"]["max_abs_C"],
            "maximum_static_wheel_angle_rad":
                acceptance_summary["maximums"][
                    "max_static_wheel_angle_rad"],
            "max_observed_solve_wall_time_s":
                acceptance_summary["deadline"][
                    "max_observed_solve_wall_time_s"],
            "timeout_point": acceptance_summary["deadline"]["timeout_point"],
            "frozen_config_sha256_canonical":
                frozen["planner_config"]["frozen_sha256_canonical"],
            "frozen_open_requests_sha256":
                frozen["files"]["open_requests.json"]["frozen_sha256"],
            "frozen_existence_reference_sha256":
                frozen["files"]["existence_reference.json"][
                    "frozen_sha256"],
            "g2_entered": True,
            "g3_entered": False,
            "nonclaims": results["nonclaims"],
        },
        "verification": {
            "script": "analysis/verify_source_manifest.py",
            "command": (
                "PYTHONDONTWRITEBYTECODE=1 python3 -B -I "
                "$RUN/analysis/verify_source_manifest.py"),
            "log": "logs/source_manifest_verification.log",
            "rule": (
                "Recompute every source and run-file SHA-256, rehash the G0 "
                "and accepted G1 protected snapshots from disk, recompute "
                "their canonical trees, recheck the protection whitelist, "
                "the frozen config/requests, the acceptance maxima, the 97 "
                "benchmark checks, test logs, attempt count and git state."),
        },
    }
    target = RUN / "source_manifest.json"
    target.write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8")
    print(json.dumps({
        "status": "WRITTEN",
        "run_id": RUN_ID,
        "manifest": str(target.relative_to(REPO_ROOT)),
        "manifest_sha256": sha256(target),
        "manifest_bytes": target.stat().st_size,
        "source_file_count": len(source_files),
        "run_file_count": len(run_files),
        "run_total_bytes": run_total_bytes,
        "excluded_self_referential": EXCLUSIONS,
        "protected_added": added,
        "protected_changed": changed,
        "protected_removed": [],
    }, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()